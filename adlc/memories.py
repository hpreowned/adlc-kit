"""Committed Serena memories derived from the contract (AGENTS.md) and the graph report.
Regenerated by `adlc baseline`; same freshness stamp as the graph. Agents can read them
through Serena's `read_memory`/`list_memories`; they cannot write them (allowlist)."""
from __future__ import annotations

import re
from pathlib import Path

from adlc import contract as C

MEM_DIR = Path(".serena") / "memories"


def _section(text: str, heading: str) -> str:
    m = re.search(rf"^## {re.escape(heading)}.*?$(.*?)(?=^## |\Z)", text, re.M | re.S)
    return m.group(1).strip() if m else ""


def contract_memory(repo: Path) -> str:
    text = (repo / "AGENTS.md").read_text()
    c = C.parse(text)
    parts = [f"# adlc_contract — {repo.name}", "",
             "Derived from AGENTS.md by `adlc baseline`; do not edit here, edit AGENTS.md.", ""]
    for h in ("Build, test, run, lint", "Conventions", "Do not touch", "Where things are explained"):
        body = _section(text, h)
        if body:
            parts += [f"## {h}", body, ""]
    for svc in sorted(repo.glob("*/AGENTS.md")):
        parts += [f"## Service: {svc.parent.name}", svc.read_text().split("\n", 2)[-1].strip(), ""]
    parts += ["## Context layer", f"- context: {', '.join(c.context)}", f"- artifact: `{c.artifact}` (check `adlc stale`)",
              f"- sensitive paths: {', '.join(c.sensitive) or 'none declared'}", ""]
    return "\n".join(parts)


def graph_memory(repo: Path, artifact: str) -> str | None:
    report = (repo / artifact).parent / "GRAPH_REPORT.md"
    if not report.exists():
        return None
    text = report.read_text()
    god = _section(text, "God Nodes (most connected - your core abstractions)") or _section(text, "God Nodes")
    summary = _section(text, "Summary")
    return "\n".join([f"# adlc_graph_summary — {repo.name}", "",
                      "Derived from graphify-out/GRAPH_REPORT.md by `adlc baseline`.", "",
                      "## Summary", summary, "", "## God nodes (start here for architecture questions)", god, "",
                      "Use `/graphify query|path|explain` for anything structural; `adlc stale` first.", ""])


def write_memories(repo: Path, artifact: str) -> list[Path]:
    d = repo / MEM_DIR
    d.mkdir(parents=True, exist_ok=True)
    written = []
    (d / "adlc_contract.md").write_text(contract_memory(repo))
    written.append(d / "adlc_contract.md")
    g = graph_memory(repo, artifact)
    if g:
        (d / "adlc_graph_summary.md").write_text(g)
        written.append(d / "adlc_graph_summary.md")
    return written
