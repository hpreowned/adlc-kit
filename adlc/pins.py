"""`adlc pins`: generate PINS.md from uv.lock + adlc/pins.json. Never hand-written."""
from __future__ import annotations

import json
import re
from pathlib import Path

from adlc.paths import kit_root

PINS_JSON = Path(__file__).with_name("pins.json")


def load_pins() -> dict:
    return json.loads(PINS_JSON.read_text())


def locked_versions(lock_path: Path) -> dict[str, str]:
    """Minimal uv.lock reader: package name -> version (no TOML parser needed)."""
    if not lock_path.exists():
        return {}
    out: dict[str, str] = {}
    cur: str | None = None
    for line in lock_path.read_text().splitlines():
        if line.strip() == "[[package]]":
            cur = None
        m = re.match(r'^name = "([^"]+)"', line)
        if m:
            cur = m.group(1)
        m = re.match(r'^version = "([^"]+)"', line)
        if m and cur and cur not in out:
            out[cur] = m.group(1)
    return out


def render(pins: dict, locked: dict[str, str]) -> str:
    g = pins["graphify"]
    s = pins["serena"]
    rows = [
        "# PINS.md — generated by `adlc pins`; do not edit\n",
        "| Component | Pin | Source of truth |", "|---|---|---|",
        f"| GitHub Copilot CLI | {pins['copilot_cli']['version']} | adlc/pins.json |",
        f"| graphifyy[leiden] | {g['version']} (lock: {locked.get('graphifyy', '—')}) sha256 `{g['wheel_sha256'][:16]}…` | uv.lock |",
        f"| Serena | commit `{s['commit'][:12]}` · context `{s['context']}` · {len(s['tools'])} tools | adlc/pins.json |",
        f"| Python | {pins['python']} | pyproject.toml |",
    ]
    for lang, ls in pins["language_servers"].items():
        if lang.startswith("_"):
            continue
        rows.append(f"| LSP {lang} | {ls['name']} {ls['version']} | pinned by Serena commit |")
    rows.append("")
    rows.append("## Locked Python packages (uv.lock)\n")
    for name in sorted(locked):
        rows.append(f"- `{name}=={locked[name]}`")
    rows.append("")
    rows.append("## Serena tool allowlist\n")
    rows.extend(f"- `{t}`" for t in s["tools"])
    rows.append("")
    rows.append(f"Serena licence: {s['license']}\n")
    return "\n".join(rows)


def add_parser(sub) -> None:
    p = sub.add_parser("pins", help="generate PINS.md from uv.lock + pins.json")
    p.add_argument("--check", action="store_true", help="exit 1 if PINS.md is out of date")
    p.set_defaults(func=run)


def run(args) -> int:
    root = kit_root()
    text = render(load_pins(), locked_versions(root / "uv.lock"))
    target = root / "PINS.md"
    if getattr(args, "check", False):
        ok = target.exists() and target.read_text() == text
        print("PINS.md up to date" if ok else "PINS.md stale — run `adlc pins`")
        return 0 if ok else 1
    target.write_text(text)
    print(f"wrote {target}")
    return 0
